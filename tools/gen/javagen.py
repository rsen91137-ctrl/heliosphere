"""Writes Java id lists from content.py so registration code and assets never drift apart."""
import os
import content as C

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))


def write_list(module, cls, fields):
    pkg = f"com.heliosphere.{module}"
    path = os.path.join(ROOT, module, 'src/main/java/com/heliosphere', module, cls + '.java')
    lines = [f"package {pkg};", "", "/** Generated by tools/gen/javagen.py from content.py - do not edit. */",
             f"public final class {cls} {{", f"    private {cls}() {{}}"]
    for name, rows in fields.items():
        lines.append(f"    public static final String[][] {name} = {{")
        for r in rows:
            lines.append("        {" + ", ".join('"%s"' % x for x in r) + "},")
        lines.append("    };")
    lines.append("}")
    open(path, 'w', encoding='utf-8').write("\n".join(lines) + "\n")


def main():
    write_list('industry', 'GenIds', {
        'ORES': [(o[0], o[12], o[3]) for o in C.ORES],
        'ITEMS': [(i[1],) for i in C.ITEMS if i[0] == 'industry'],
        'MACHINES': [(m[1],) for m in C.MACHINES if m[0] == 'industry'],
    })
    write_list('planets', 'GenIds', {
        'ITEMS': [(i[1],) for i in C.ITEMS if i[0] == 'planets'],
        'MACHINES': [(m[1],) for m in C.MACHINES if m[0] == 'planets'],
    })


if __name__ == '__main__':
    main()


def write_guide():
    import guide_content as G
    ids = []
    for c in G.CHAPTERS:
        for o in c["objectives"]:
            if o not in ids:
                ids.append(o)
    path = os.path.join(ROOT, 'guide/src/main/java/com/heliosphere/guide/GenGuide.java')
    body = ",\n            ".join('"%s"' % i for i in ids)
    open(path, 'w', encoding='utf-8').write(f"""package com.heliosphere.guide;

import java.util.Set;

/** Generated by tools/gen/javagen.py from guide_content.py - do not edit. */
public final class GenGuide {{
    private GenGuide() {{}}
    public static final Set<String> OBJECTIVES = Set.of(
            {body});
}}
""")


write_guide()
