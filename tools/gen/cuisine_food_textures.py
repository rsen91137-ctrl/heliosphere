def colour(v):
    """'#rrggbb[aa]' a body pixel, '!#..' an outline pixel, '~#..' a soft pixel (glass, steam: no outline round it),
    None clears the pixel."""
    if v is None:
        return (0, 0, 0, 0), EMPTY
    kind = BODY
    if v[0] == '!':
        kind, v = EDGE, v[1:]
    elif v[0] == '~':
        kind, v = SOFT, v[1:]
    h = v.lstrip('#')
    c = [int(h[i:i + 2], 16) for i in range(0, len(h), 2)]
    if len(c) == 3:
        c.append(255)
    return tuple(c), kind


def parse(s):
    """A character grid: rows of equal width; leading indentation is ignored."""
    lines = [ln.strip() for ln in textwrap.dedent(s).strip('\n').split('\n')]
    assert len({len(ln) for ln in lines}) == 1, [len(ln) for ln in lines]
    return lines


def edge_colour(rgb):
    """The outline next to a material: the material darkened to about a quarter. Pale materials get a near-neutral
    dark (a cream would otherwise give a muddy olive), yellows turn brown, greys and whites a cool slate."""
    r, g, b = (float(v) / 255 for v in rgb)
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    l2 = min(0.15, l * 0.32)
    if s <= 0.08:
        h, s2 = 0.63, 0.24
    else:
        s2 = s * min(1.0, (1.0 - l) * 2.4)
        if 0.09 < h < 0.2:
            h = 0.07
    rr, gg, bb = colorsys.hls_to_rgb(h, l2, s2)
    return tuple(int(round(v * 255)) for v in (rr, gg, bb)) + (255,)


class Tex:
    def __init__(self, n=16):
        self.n = n
        self.px = np.zeros((n, n, 4), np.uint8)
        self.kind = np.zeros((n, n), np.int8)

    def put(self, grid, pal, dx=0, dy=0):
        g = parse(grid) if isinstance(grid, str) else grid
        for j, line in enumerate(g):
            for i, ch in enumerate(line):
                if ch == '.':
                    continue
                x, y = dx + i, dy + j
                assert 0 <= x < self.n and 0 <= y < self.n, (ch, x, y)
                assert ch in pal, ('no colour for', ch)
                c, k = colour(pal[ch])
                self.px[y, x] = c
                self.kind[y, x] = k
        return self

    def outline(self):
        n = self.n
        add = []
        for y in range(n):
            for x in range(n):
                if self.kind[y, x] != EMPTY:
                    continue
                nb = [self.px[y + dy, x + dx, :3] for dx, dy in N4
                      if 0 <= x + dx < n and 0 <= y + dy < n and self.kind[y + dy, x + dx] == BODY]
                if nb:
                    darkest = min(nb, key=lambda c: int(c[0]) * 3 + int(c[1]) * 6 + int(c[2]))
                    add.append((y, x, edge_colour(darkest)))
        for y, x, c in add:
            self.px[y, x] = c
            self.kind[y, x] = EDGE
        return self

    def image(self):
        return Image.fromarray(self.px.copy(), 'RGBA')


def make(*layers, n=16, outline=True):
    """Composite (grid, palette[, dx, dy]) layers in order and outline the result."""
    t = Tex(n)
    for layer in layers:
        t.put(*layer)
    if outline:
        t.outline()
    return t


def item(grid, pal):
    """A single outlined 16x16 grid."""
    return make((grid, pal))


def compose(*items, n=16):
    """Stamp (grid, x, y) character grids onto an empty n x n grid, later ones on top; returns the rows."""
    g = [['.'] * n for _ in range(n)]
    for item in items:
        spr, x, y = (item, 0, 0) if isinstance(item, (str, list)) else item
        for j, line in enumerate(parse(spr) if isinstance(spr, str) else spr):
            for i, ch in enumerate(line):
                if ch != '.' and 0 <= x + i < n and 0 <= y + j < n:
                    g[y + j][x + i] = ch
    return [''.join(r) for r in g]


def rod(x0, y0, x1, y1, w, light, mid, dark, n=16, flat=False):
    """A straight round stick between two pixel centres, w pixels thick, shaded across: the side facing the top left
    light, the far side dark; round ends, or cut square at the end points (flat). Returns a character grid."""
    dx, dy = x1 - x0, y1 - y0
    length = (dx * dx + dy * dy) ** 0.5
    ux, uy = dx / length, dy / length
    px, py = -uy, ux                                   # a normal of the stick ...
    if px + py > 0:                                    # ... turned to face the top left
        px, py = -px, -py
    g = []
    for y in range(n):
        row = ''
        for x in range(n):
            t = (x - x0) * ux + (y - y0) * uy
            if flat and not -0.01 <= t <= length + 0.01:
                row += '.'
                continue
            t = max(0.0, min(length, t))
            ex, ey = x - (x0 + ux * t), y - (y0 + uy * t)
            if ex * ex + ey * ey > (w / 2.0) ** 2 + 0.02:
                row += '.'
                continue
            side = ex * px + ey * py
            row += light if side > w / 6.0 else dark if side < -w / 6.0 else mid
        g.append(row)
    return g


def pad(s, n=16):
    """A grid written with only its top rows: padded with empty rows to n."""
    g = parse(s)
    return g + ['.' * len(g[0])] * (n - len(g))


