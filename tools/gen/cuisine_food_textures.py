def bowl(food, pal, soup=False, wood=False):
    """A dish in a bowl: the far rim, the food (a 16x16 grid), then the near rim and the body."""
    base = WOOD if wood else BOWL
    back, front = (SOUP_BACK, SOUP_FRONT) if soup else (BOWL_BACK, parse(BOWL_FRONT))
    if wood:
        front = [r.replace('56666677', '33222110') for r in front]
    p = dict(base)
    p.update(pal)
    return make((back, base), (pad(food) if isinstance(food, str) else food, p), (front, base))


def soup(food, pal, wood=False):
    return bowl(food, pal, soup=True, wood=wood)


