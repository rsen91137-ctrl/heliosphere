#!/usr/bin/env python3
"""Item textures of the food expansion (overlay jars/04-foods) that are not crops: the kitchen ingredients, the
dishes, the hand tools and the seed packet (textures/item/<id>.png, 16x16), and the food buff icons
(textures/mob_effect/<id>.png, 18x18), drawn after the 'look' notes in cuisine_spec.py.

Every texture is hand-placed pixel art written as character grids: a character is one fixed colour of the
texture's palette (three or four tones per material, light from the top left). Shared parts (the porcelain bowl,
the vanilla-style glass bottle, the plate, the bamboo steamer ...) are grids of their own; a dish is composited from
the back of its container, the food and the front of the container. At the end a dark outline is added round the
silhouette, coloured from the material it surrounds (glass and steam get none, like the vanilla bottle).
No randomness, no timestamps: two runs give byte-identical files.

    python3 tools/gen/cuisine_food_textures.py [--sheet review.png] [--only id,id]
"""
