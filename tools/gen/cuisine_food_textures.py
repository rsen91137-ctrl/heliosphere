def all_ids():
    """Every texture this generator owns: (id, folder, size)."""
    out = [(i[0], 'item', 16) for i in SPEC.INGREDIENTS]
    out += [(d[0], 'item', 16) for d in SPEC.DISHES]
    out += [(t[0], 'item', 16) for t in SPEC.TOOLS]
    out += [(o[0], 'item', 16) for o in SPEC.OTHER]
    out += [(e[0], 'mob_effect', 18) for e in SPEC.EFFECTS]
    return out


def sheet(images, path, scale=6, columns=10):
    """Every texture enlarged on an inventory-slot grey, with its id and a 2x copy (the size in a GUI)."""
    font = ImageFont.load_default(size=11)
    cw, ch = 18 * scale + 16, 18 * scale + 58
    rows = (len(images) + columns - 1) // columns
    img = Image.new('RGBA', (columns * cw, rows * ch), (198, 198, 198, 255))
    d = ImageDraw.Draw(img)
    for k, (name, im) in enumerate(images):
        x0, y0 = (k % columns) * cw, (k // columns) * ch
        d.rectangle([x0 + 4, y0 + 4, x0 + 11 + 18 * scale, y0 + 11 + 18 * scale], fill=(139, 139, 139, 255),
                    outline=(55, 55, 55, 255))
        big = im.resize((im.width * scale, im.height * scale), Image.NEAREST)
        off = (18 - im.width) * scale // 2
        img.alpha_composite(big, (x0 + 8 + off, y0 + 8 + off))
        sy = y0 + 18 * scale + 15
        d.rectangle([x0 + 4, sy, x0 + 43, sy + 39], fill=(139, 139, 139, 255), outline=(55, 55, 55, 255))
        small = im.resize((im.width * 2, im.height * 2), Image.NEAREST)
        img.alpha_composite(small, (x0 + 6 + (18 - im.width), sy + 2 + (18 - im.width)))
        d.text((x0 + 48, sy + 2), name[:13], fill=(20, 20, 20, 255), font=font)
        if len(name) > 13:
            d.text((x0 + 48, sy + 15), name[13:], fill=(20, 20, 20, 255), font=font)
    img.save(path)


def main(argv):
    only = None
    sheet_path = None
    if '--only' in argv:
        only = set(argv[argv.index('--only') + 1].split(','))
    if '--sheet' in argv:
        sheet_path = argv[argv.index('--sheet') + 1]
    ids = all_ids()
    missing = [i for i, _, _ in ids if i not in T]
    extra = sorted(set(T) - {i for i, _, _ in ids})
    assert not extra, ('drawings for unknown ids', extra)
    images = []
    for name, folder, n in ids:
        if name not in T or (only and name not in only):
            continue
        t = T[name]()
        assert t.n == n, (name, t.n)
        im = t.image()
        out = os.path.join(TEX, folder, name + '.png')
        os.makedirs(os.path.dirname(out), exist_ok=True)
        im.save(out, optimize=False)
        images.append((name, im))
    if sheet_path:
        sheet(images, sheet_path)
    print(f'{len(images)} textures written' + (f', {len(missing)} not drawn yet' if missing else ''))


if __name__ == '__main__':
    main(sys.argv[1:])
