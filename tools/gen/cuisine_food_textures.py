@tex
def kitchen_knife():
    # a broad cleaver: a rectangle of steel turned 45 degrees (spine top left, bright edge bottom right), a hole near
    # the front corner, a wooden handle going down to the left
    g = [['.'] * 16 for _ in range(16)]
    for y in range(16):
        for x in range(16):
            if max(11 - y, y - 3) <= x <= min(y + 9, 19 - y):
                d = x + y
                g[y][x] = 'S' if d <= 12 else 'e' if d >= 18 else 'b' if d == 17 else 'm' if x - y >= 8 else 'M'
