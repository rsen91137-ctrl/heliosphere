def trefoil(cx=9.0, cy=8.6, r0=1.9, r1=5.0):
    """The radiation sign: a centre dot and three blades (up, lower left, lower right)."""
    rows = []
    for y in range(18):
        row = ''
        for x in range(18):
            dx, dy = x + 0.5 - cx, y + 0.5 - cy
            r = math.hypot(dx, dy)
            a = math.degrees(math.atan2(dy, dx)) % 360
            blade = any(abs((a - c + 180) % 360 - 180) <= 30 for c in (270, 30, 150))
            row += 'T' if r < 1.15 or (r0 <= r <= r1 and blade) else '.'
        rows.append(row)
    return '\n'.join(rows)


